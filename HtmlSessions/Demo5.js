//  find the big number from two numbers
// use fun with arg and without return value

function  BigNumber(x, y)
{
    if(x>y)
        console.log(x + " and " + y + " Big Number is " + x);
    else
        console.log(x + " and " + y + " Big Number is " + y);
}

// fun callings
BigNumber(10, 5);
BigNumber(20, 30);

